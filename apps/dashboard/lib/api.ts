/**
 * Typed API client for the local AgentFence backend.
 *
 * Base URL comes from NEXT_PUBLIC_AGENTFENCE_API and defaults to the local
 * API started with `agentfence dashboard` (http://127.0.0.1:8000).
 */

export const API_BASE_URL =
  process.env.NEXT_PUBLIC_AGENTFENCE_API ?? "http://127.0.0.1:8000";

export type Severity =
  | "critical"
  | "high"
  | "medium"
  | "low"
  | "info";

export interface FindingDto {
  finding_pk: number;
  scan_id: string;
  rule_id: string;
  title: string;
  description: string;
  severity: Severity;
  file_ref: string | null;
  remediation: string;
  evidence: string | null;
}

export interface ScanSummaryDto {
  scan_id: string;
  created_at: string;
  target_display: string;
  status: string;
  scanner_version: string;
  risk_score: number;
  files_inspected: number;
  total_findings: number;
  critical_findings: number;
  high_findings: number;
  medium_findings: number;
  low_findings: number;
  info_findings: number;
  kind: string;
}

export interface ScanDetailDto {
  scan: ScanSummaryDto;
  findings: FindingDto[];
}

export interface ScanListDto {
  scans: ScanSummaryDto[];
  total: number;
  limit: number;
  offset: number;
}

export interface SummaryDto {
  total_scans: number;
  total_findings: number;
  critical: number;
  high: number;
  medium: number;
  low: number;
  info: number;
}

export interface ScanStartedDto {
  scan_id: string;
  result: {
    target: string;
    scanner: string;
    files_inspected: number;
    findings: {
      id: string;
      title: string;
      severity: Severity;
      category: string;
      description: string;
      remediation: string;
      file: string | null;
      evidence: string | null;
    }[];
  };
  risk_score: number;
}

export class ApiError extends Error {
  constructor(
    message: string,
    readonly status: number,
  ) {
    super(message);
    this.name = "ApiError";
  }
}

/**
 * The API requires a local session token on mutating requests to prevent
 * untrusted websites from driving the local API. The token is generated by
 * the API (stored at .agentfence/.api-token) and supplied to the dashboard
 * via NEXT_PUBLIC_AGENTFENCE_TOKEN for local development.
 */
const SESSION_TOKEN = process.env.NEXT_PUBLIC_AGENTFENCE_TOKEN ?? "";

async function request<T>(path: string, init?: RequestInit): Promise<T> {
  const headers = new Headers(init?.headers);
  if (init?.method && init.method !== "GET" && SESSION_TOKEN) {
    headers.set("X-AgentFence-Session", SESSION_TOKEN);
  }
  let response: Response;
  try {
    response = await fetch(`${API_BASE_URL}${path}`, {
      cache: "no-store",
      ...init,
      headers,
    });
  } catch {
    throw new ApiError(
      `Cannot reach the AgentFence API at ${API_BASE_URL}. Start it with \`agentfence dashboard\`.`,
      0,
    );
  }
  if (!response.ok) {
    let detail = `${response.status} ${response.statusText}`;
    try {
      const body = (await response.json()) as { detail?: string };
      if (body?.detail) detail = body.detail;
    } catch {
      // keep status-based message
    }
    throw new ApiError(detail, response.status);
  }
  return (await response.json()) as T;
}

export const api = {
  health: () => request<{ status: string; version: string }>("/api/v1/health"),

  summary: () => request<SummaryDto>("/api/v1/summary"),

  listScans: (params?: {
    limit?: number;
    offset?: number;
    order?: "asc" | "desc";
    severity?: Severity;
  }) => {
    const qs = new URLSearchParams();
    if (params?.limit !== undefined) qs.set("limit", String(params.limit));
    if (params?.offset !== undefined) qs.set("offset", String(params.offset));
    if (params?.order) qs.set("order", params.order);
    if (params?.severity) qs.set("severity", params.severity);
    const suffix = qs.toString() ? `?${qs.toString()}` : "";
    return request<ScanListDto>(`/api/v1/scans${suffix}`);
  },

  getScan: (scanId: string) =>
    request<ScanDetailDto>(`/api/v1/scans/${encodeURIComponent(scanId)}`),

  runScan: (path: string) =>
    request<ScanStartedDto>("/api/v1/scan", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ path }),
    }),

  inspectMcp: (path: string) =>
    request<ScanStartedDto>("/api/v1/mcp/inspect", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ path }),
    }),

  arenaScenarios: () =>
    request<
      { name: string; description: string; tags: string[]; expected_decision: string }[]
    >("/api/v1/arena/scenarios"),

  arenaRun: (scenarioIds?: string[]) =>
    request<ArenaRunDto>("/api/v1/arena/run", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ scenario_ids: scenarioIds?.length ? scenarioIds : null }),
    }),

  arenaRuns: (limit = 20, offset = 0) =>
    request<ArenaRunListDto>(`/api/v1/arena/runs?limit=${limit}&offset=${offset}`),

  arenaRunDetail: (runId: string) =>
    request<ArenaRunDto>(`/api/v1/arena/runs/${encodeURIComponent(runId)}`),

  policies: () =>
    request<{
      policies: {
        name: string;
        file: string;
        directory: string;
        valid: boolean;
        problems: string[];
        default: string | null;
        rule_count: number;
        rules: {
          id: string;
          action: string;
          resource: string;
          decision: string;
          description: string | null;
        }[];
      }[];
    }>("/api/v1/policies"),

  policyValidate: (content: string) =>
    request<{ valid: boolean; problems: string[] }>("/api/v1/policies/validate", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ content }),
    }),

  policyEvaluate: (body: {
    name?: string;
    content?: string;
    action: string;
    resource: string;
  }) =>
    request<PolicyEvaluationDto>("/api/v1/policies/evaluate", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body),
    }),

  policyHistory: (limit = 20, offset = 0) =>
    request<{
      evaluations: {
        evaluation_id: string;
        created_at: string;
        policy_name: string;
        policy_valid: boolean;
        action: string;
        resource: string;
        decision: string;
        matched_rule: string | null;
        explanation: string;
      }[];
      limit: number;
      offset: number;
    }>(`/api/v1/policies/history?limit=${limit}&offset=${offset}`),
};

